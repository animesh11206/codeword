#include <filesystem>
#include <iostream>
#include <string>
#include "display_help.h"

namespace {

std::string resolved_prog_name(const std::string& prog_name) {
    if (prog_name.empty()) {
        return "codeword";
    }
    std::error_code ec;
    std::filesystem::path p(prog_name);
    std::string fname = p.filename().string();
    return fname.empty() ? prog_name : fname;
}

std::string resolved_version() {
    return VERSION.empty() ? "1.0.0" : VERSION;
}

std::string resolved_author() {
    return AUTHOR.empty() ? "Codeword Contributors" : AUTHOR;
}

} // namespace

void display_version() {
    std::cout << "codeword version " << resolved_version() << "\n"
              << "Author: " << resolved_author() << "\n"
              << "Built with C++17 (36 Encoders | 36 Decoders | 49 Hash Algorithms)\n";
}

